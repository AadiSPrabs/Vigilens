const http = require('http')
const WebSocket = require('C:/Users/admin/Documents/Vigilens/frontend/node_modules/ws')
const HOST='127.0.0.1', PORT=9222
function httpJson(method,path){return new Promise((res,rej)=>{const r=http.request({host:HOST,port:PORT,method,path},x=>{let d='';x.on('data',c=>d+=c);x.on('end',()=>{try{res(d?JSON.parse(d):null)}catch(e){rej(new Error(d))}})});r.on('error',rej);r.end()})}
const sleep=ms=>new Promise(r=>setTimeout(r,ms))
async function main(){
  const t=await httpJson('PUT','/json/new?about:blank')
  const ws=new WebSocket(t.webSocketDebuggerUrl)
  let id=1;const p=new Map()
  ws.on('message',raw=>{const m=JSON.parse(raw);if(m.id&&p.has(m.id)){const {res,rej}=p.get(m.id);p.delete(m.id);m.error?rej(new Error(JSON.stringify(m.error))):res(m.result)}})
  await new Promise((r,j)=>{ws.on('open',r);ws.on('error',j)})
  const send=(method,params={})=>new Promise((res,rej)=>{const i=id++;p.set(i,{res,rej});ws.send(JSON.stringify({id:i,method,params}))})
  const ev=async e=>{const r=await send('Runtime.evaluate',{expression:e,returnByValue:true,awaitPromise:true,userGesture:true});if(r.exceptionDetails)throw new Error(r.exceptionDetails.text+' '+(r.exceptionDetails.exception&&r.exceptionDetails.exception.description));return r.result.value}
  const wait=async(e,t=8000)=>{const s=Date.now();while(Date.now()-s<t){if(await ev(e))return true;await sleep(100)}throw new Error('timeout '+e)}
  const press=async(key)=>{const code=key===' '?'Space':key;const vk=key==='Enter'?13:32;const text=key===' '?' ':(key==='Enter'?'\r':undefined);await send('Input.dispatchKeyEvent',{type:'keyDown',key,code,windowsVirtualKeyCode:vk,text});await send('Input.dispatchKeyEvent',{type:'keyUp',key,code,windowsVirtualKeyCode:vk});await sleep(200)}
  await send('Page.enable');await send('Runtime.enable')
  await send('Emulation.setDeviceMetricsOverride',{width:1280,height:1000,deviceScaleFactor:1,mobile:false})
  await send('Page.navigate',{url:'http://127.0.0.1:5176/'})
  await wait(`!!document.querySelector('.sample-btn')`)
  await ev(`localStorage.setItem('vigilens-theme','light')`)
  await ev(`(() => { const b=[...document.querySelectorAll('.sample-btn')].find(x=>x.textContent.trim()==='sample-3'); b.click(); return true })()`)
  await wait(`!!document.querySelector('.zone-canvas-wrapper img')`)
  await sleep(400)
  await ev(`(() => { const a=document.querySelector('.analyse-btn'); a.click(); return true })()`)
  await wait(`!!document.querySelector('[role="tablist"]')`,15000)
  await sleep(800)
  console.log('ROW HTML', (await ev(`document.querySelector('.finding-row').outerHTML`)).slice(0,2500))
  console.log('RECTS', JSON.stringify(await ev(`(() => { const r=document.querySelector('.finding-row'); const out={}; for (const sel of ['.finding-row','.finding-person','.finding-ppe','.finding-meta','.finding-message','.review','.finding-recheck']) { const e=r.querySelector(sel); if(e){const b=e.getBoundingClientRect(); const c=getComputedStyle(e); out[sel]={x:b.x,y:b.y,w:b.width,h:b.height,display:c.display,visibility:c.visibility,opacity:c.opacity,fontSize:c.fontSize,overflow:c.overflow}} } return out })()`),null,2))
  console.log('TEXT', await ev(`document.querySelector('.finding-row').innerText`))
  console.log('PPE TEXT', await ev(`document.querySelector('.finding-ppe') ? document.querySelector('.finding-ppe').innerText : null`))
  console.log('ENTER')
  await ev(`document.querySelector('.finding-person').focus()`)
  console.log('focus',await ev(`document.activeElement.className`))
  await press('Enter')
  console.log('after enter',await ev(`document.querySelectorAll('.finding-row.is-selected').length`))
  await press(' ')
  console.log('after space',await ev(`document.querySelectorAll('.finding-row.is-selected').length`))
  await httpJson('GET',`/json/close/${t.id}`);ws.close()
}
main().catch(e=>{console.error(e.stack||e);process.exit(1)})
